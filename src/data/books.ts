export function getBookCoverUrl(book: Book): string {
  if (book.coverUrl) return book.coverUrl;
  if (typeof book.coverId === 'string' && book.coverId.startsWith('isbn:')) {
    return `https://covers.openlibrary.org/b/isbn/${book.coverId.replace('isbn:', '')}-L.jpg`;
  }
  return `https://covers.openlibrary.org/b/id/${book.coverId}-L.jpg`;
}
